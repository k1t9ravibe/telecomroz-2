export interface AreaRange {
  id: string;
  label: string;
  min: number;
  max: number;
}

/** Диапазоны площади для группировки сопоставимых объектов (м², [min; max)). */
export const AREA_RANGES: AreaRange[] = [
  { id: 'a1', label: 'до 50 м²', min: 0, max: 50 },
  { id: 'a2', label: '50–100 м²', min: 50, max: 100 },
  { id: 'a3', label: '100–250 м²', min: 100, max: 250 },
  { id: 'a4', label: '250–500 м²', min: 250, max: 500 },
  { id: 'a5', label: '500–1000 м²', min: 500, max: 1000 },
  { id: 'a6', label: 'свыше 1000 м²', min: 1000, max: Number.POSITIVE_INFINITY },
];

export function areaRangeOf(area: number): AreaRange {
  return AREA_RANGES.find((r) => area >= r.min && area < r.max) ?? AREA_RANGES[AREA_RANGES.length - 1];
}

